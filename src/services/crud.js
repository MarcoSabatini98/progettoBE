// Operazioni base per le tabelle gestite dal pannello admin (tipologie,
// periodi tariffari, FAQ...). I service specifici aggiungono le regole proprie
// e usano queste per il resto. Gli errori del DB li traduce il middleware.

const { oppure404 } = require('../utils/errori');
const { pagina, risultato } = require('../utils/paginazione');

/**
 * @param {import('sequelize').ModelStatic<any>} Modello
 * @param {{ codice: string, messaggio: string, ordine?: any[], include?: any[], campi?: string[] }} opzioni
 *   codice/messaggio: errore 404; campi: colonne scrivibili dal client
 */
function crud(Modello, { codice, messaggio, ordine = [['id', 'ASC']], include = [], campi }) {
  const attributi = Modello.getAttributes();
  const scrivibili =
    campi ??
    Object.keys(attributi).filter(
      (c) =>
        !attributi[c].primaryKey &&
        !attributi[c]._autoGenerated &&
        ![
          'uuid',
          'creato_da',
          'aggiornato_da',
          'creato_il',
          'aggiornato_il',
          'eliminato_il',
        ].includes(c) &&
        attributi[c].type.key !== 'VIRTUAL' &&
        !attributi[c].set,
    );

  const filtra = (dati) =>
    Object.fromEntries(scrivibili.filter((c) => dati[c] !== undefined).map((c) => [c, dati[c]]));

  const autore = (contesto, nuovo) => ({
    ...(nuovo && attributi.creato_da ? { creato_da: contesto?.utenteId ?? null } : {}),
    ...(attributi.aggiornato_da ? { aggiornato_da: contesto?.utenteId ?? null } : {}),
  });

  const dettaglio = async (id, opzioni = {}) =>
    oppure404(await Modello.findByPk(id, { include, ...opzioni }), codice, messaggio);

  return {
    Modello,
    campi: scrivibili,

    /** Elenco; con query.pagina restituisce la pagina, altrimenti tutto. */
    async elenco(query = {}, where = {}) {
      if (query.pagina === undefined) return Modello.findAll({ where, include, order: ordine });
      const p = pagina(query);
      const righe = await Modello.findAndCountAll({
        where,
        include,
        order: ordine,
        limit: p.limit,
        offset: p.offset,
        distinct: true,
      });
      return risultato(righe, p);
    },

    dettaglio,

    async crea(dati, contesto, transaction) {
      const record = await Modello.create(
        { ...filtra(dati), ...autore(contesto, true) },
        { transaction },
      );
      return transaction ? record : dettaglio(record.id ?? record.get(Modello.primaryKeyAttribute));
    },

    async aggiorna(id, dati, contesto, transaction) {
      const record = await dettaglio(id, { include: [], transaction });
      await record.update({ ...filtra(dati), ...autore(contesto, false) }, { transaction });
      return transaction ? record : dettaglio(id);
    },

    async elimina(id, transaction) {
      const record = await dettaglio(id, { include: [], transaction });
      await record.destroy({ transaction });
      return record;
    },
  };
}

module.exports = { crud };
